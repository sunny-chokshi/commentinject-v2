"""Build the twin-review materials from data/pairs.jsonl (read-only input).

Usage: python3 -I scripts/build_twin_review.py review/TWIN_REVIEW_2026-11-24

Writes:
  blinded/BLINDED_PAIRS.md     30 items in shuffled order; snippets A/B in random order; no labels, CWEs or comments
  blinded/REVIEW_FORM.csv      one row per item for the human reviewer
  key/UNBLINDING_KEY.csv       blind id -> pair id, which snippet is safe, CWE  (DO NOT give to the reviewer)
  DIFF_REPORT.md, diff_metrics.csv   mechanical differences per pair (size, imports, signature, added names, unified diff)
Seed 20261124 (fixed) so the blinding is reproducible.
"""
import ast, csv, difflib, io, json, os, random, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import DATA, load_jsonl

SEED = 20261124

def facts(code):
    t = ast.parse(code)
    imports = sorted({a.name for n in ast.walk(t) if isinstance(n, (ast.Import, ast.ImportFrom))
                      for a in n.names} | {n.module for n in ast.walk(t) if isinstance(n, ast.ImportFrom) and n.module})
    fns = [n for n in t.body if isinstance(n, ast.FunctionDef)]
    sig = [f"{f.name}({', '.join(a.arg for a in f.args.args)})" for f in fns]
    names = {n.id for n in ast.walk(t) if isinstance(n, ast.Name)} | {n.attr for n in ast.walk(t) if isinstance(n, ast.Attribute)}
    raises = sum(isinstance(n, ast.Raise) for n in ast.walk(t))
    returns = any(isinstance(n, ast.Return) and n.value is not None for f in fns for n in ast.walk(f))
    return dict(lines=code.count("\n") + 1, chars=len(code), nodes=sum(1 for _ in ast.walk(t)),
                imports=imports, sig=sig, names=names, raises=raises, returns=returns)

def main(out):
    pairs = load_jsonl(os.path.join(DATA, "pairs.jsonl"))
    rng = random.Random(SEED)
    order = pairs[:]; rng.shuffle(order)
    os.makedirs(os.path.join(out, "blinded"), exist_ok=True); os.makedirs(os.path.join(out, "key"), exist_ok=True)
    md = ["# Blinded twin review: 30 items", "",
          "Each item has two Python snippets, A and B. In every item exactly one snippet is intended to contain a security",
          "vulnerability and the other is intended to be a minimal, safe fix of it. **The order is random.** Undefined globals",
          "(`cursor`, `db`, `requests`, `url`, ...) are intentional. Judge each snippet on its own first, then compare.",
          "Record answers in `REVIEW_FORM.csv`. Do not look for or open any answer key until you have finished.", ""]
    form, key = [], []
    for i, p in enumerate(order, 1):
        bid = f"P{i:02d}"
        safe_first = rng.random() < 0.5
        a, b = (p["safe_code"], p["vulnerable_code"]) if safe_first else (p["vulnerable_code"], p["safe_code"])
        md += [f"## {bid}", "", "**Snippet A**", "", "```python", a, "```", "", "**Snippet B**", "", "```python", b, "```", ""]
        form.append({"blind_id": bid, "A_vulnerable_Y_N_unsure": "", "A_cwe_if_any": "", "B_vulnerable_Y_N_unsure": "",
                     "B_cwe_if_any": "", "same_purpose_and_behaviour_for_normal_input_Y_N": "",
                     "fix_complete_Y_N_NA": "", "new_issue_in_fixed_snippet": "", "giveaway_besides_the_flaw": "",
                     "confidence_1to5": "", "notes": ""})
        key.append({"blind_id": bid, "pair_id": p["pair_id"], "cwe": p["cwe"], "name": p["name"],
                    "safe_snippet": "A" if safe_first else "B"})
    open(os.path.join(out, "blinded", "BLINDED_PAIRS.md"), "w").write("\n".join(md) + "\n")
    for path, rows in ((os.path.join(out, "blinded", "REVIEW_FORM.csv"), form), (os.path.join(out, "key", "UNBLINDING_KEY.csv"), key)):
        with open(path, "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)

    rep = ["# Mechanical difference report (vulnerable vs safe twin)", "",
           "Generated by scripts/build_twin_review.py from data/pairs.jsonl. Size ratio = safe/vulnerable characters.",
           "`added names` = identifiers/attributes present only in the safe twin (likely cue words for a detector).", "",
           "| Pair | CWE | lines v→s | chars ratio | signature same | imports added | imports removed | raises added | added names |",
           "|---|---|---|---|---|---|---|---|---|"]
    met, diffs = [], []
    for p in pairs:
        v, s = facts(p["vulnerable_code"]), facts(p["safe_code"])
        ia = sorted(set(s["imports"]) - set(v["imports"])); ir = sorted(set(v["imports"]) - set(s["imports"]))
        added = sorted(s["names"] - v["names"])
        ratio = s["chars"] / v["chars"]
        rec = dict(pair_id=p["pair_id"], cwe=p["cwe"], lines_v=v["lines"], lines_s=s["lines"], chars_v=v["chars"], chars_s=s["chars"],
                   chars_ratio=round(ratio, 2), ast_nodes_v=v["nodes"], ast_nodes_s=s["nodes"], signature_same=v["sig"] == s["sig"],
                   returns_v=v["returns"], returns_s=s["returns"], imports_added=" ".join(ia), imports_removed=" ".join(ir),
                   raises_added=s["raises"] - v["raises"], added_names=" ".join(added))
        met.append(rec)
        rep.append(f"| {p['pair_id']} | {p['cwe']} | {v['lines']}→{s['lines']} | {ratio:.2f} | {'yes' if rec['signature_same'] else '**NO**'} | "
                   f"{', '.join(ia) or '-'} | {', '.join(ir) or '-'} | {rec['raises_added']} | {', '.join(added) or '-'} |")
        d = difflib.unified_diff(p["vulnerable_code"].splitlines(), p["safe_code"].splitlines(), "vulnerable", "safe", lineterm="")
        diffs += [f"### {p['pair_id']} ({p['cwe']} {p['name']})", "", "```diff", *d, "```", ""]
    r = [m["chars_ratio"] for m in met]
    rep += ["", "## Summary", "",
            f"- Safe twin longer than vulnerable in {sum(x > 1.0 for x in r)}/30 pairs; median size ratio {sorted(r)[15]:.2f}; max {max(r):.2f}.",
            f"- Signature identical in {sum(m['signature_same'] for m in met)}/30.",
            f"- Twin adds an import in {sum(bool(m['imports_added']) for m in met)}/30 and a `raise` in {sum(m['raises_added'] > 0 for m in met)}/30.",
            f"- Return-value presence differs in {sum(m['returns_v'] != m['returns_s'] for m in met)}/30.", "",
            "## Unified diffs", "", *diffs]
    open(os.path.join(out, "DIFF_REPORT.md"), "w").write("\n".join(rep) + "\n")
    with open(os.path.join(out, "diff_metrics.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(met[0])); w.writeheader(); w.writerows(met)
    print("\n".join(rep[:40 + 6]))

if __name__ == "__main__":
    main(sys.argv[1])
